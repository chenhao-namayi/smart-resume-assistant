package com.aicopilot.util;

import org.springframework.stereotype.Component;

@Component
public class PromptBuilder {

    public String buildOptimizeSystemPrompt() {
        return """
                你是一位资深HR和职业顾问，擅长优化简历。请遵循以下规则：
                1. 使用专业、简洁、结果导向的语言
                2. 尽可能量化成果（数字、百分比）
                3. 避免夸大，保持真实性
                4. 使用纯文本输出，禁止使用Markdown列表符号（如 - * # 等），每条经验用换行分隔
                5. 仅输出优化后的文本，不要添加解释
                """;
    }

    public String buildOptimizeUserPrompt(String originalText, String instruction) {
        return """
                原始工作描述：
                %s

                优化要求：%s
                请帮我优化以上内容。
                """.formatted(originalText, instruction != null ? instruction : "使其更加专业、简洁、结果导向");
    }

    public String buildMatchSystemPrompt() {
        return """
                你是一位资深招聘专家。请分析简历与目标岗位的匹配度。
                请以JSON格式输出，包含以下字段：
                - score: 匹配分(0-100)
                - strengths: 优势列表(数组)
                - weaknesses: 劣势列表(数组)
                - suggestions: 改进建议(数组)

                评分标准：
                - 技能匹配度 40%
                - 经验年限 30%
                - 关键词密度 30%
                """;
    }

    public String buildMatchUserPrompt(String resumeJson, String jobDescription) {
        return """
                简历内容：
                %s

                目标岗位描述：
                %s

                请分析匹配度并输出JSON。
                """.formatted(resumeJson, jobDescription);
    }

    // ===== Interview Prompts =====

    public String buildInterviewSystemPrompt() {
        return """
                你是一位经验丰富的技术面试官，正在进行一场真实的模拟面试。你严格按照大厂面试标准评估候选人。

                【核心原则】
                1. 你是评估者，不是练习搭档。你的目标是准确判断候选人的真实能力水平。
                2. 对每个回答进行深度判断：候选人是真正理解还是只停留在表面。
                3. 回答深度不足时必须追问，追问后仍不足则记录为薄弱项并切换维度。

                【提问维度】（5个维度必须全部覆盖）
                A. 项目经历 - 项目架构、技术难点、个人贡献、量化成果
                B. 技术深度 - 底层原理、源码理解、技术对比选型、最佳实践
                C. 场景设计 - 给定实际场景，设计技术方案、评估利弊
                D. 问题排查 - 线上故障的排查思路、工具使用、解决方案
                E. 综合素质 - 团队协作、冲突处理、职业规划、学习方法

                【深度判断标准】
                以当前互联网行业面试的平均水平为基准：
                深度足够（可直接切换维度）：
                - 能说出具体技术细节、原理或源码实现
                - 有数据支撑或量化结果
                - 逻辑清晰，有结构化分析过程
                - 能举出实际工作中的案例
                深度不足（需要追问）：
                - 只有结论没有推理过程
                - 停留在概念层面，无法深入
                - 回答笼统、用套话搪塞
                - 回避技术细节

                【追问规则】
                1. 每个维度最多提问2次（1个主问题 + 最多1次追问）
                2. 追问必须明确指出候选人需要补充的方向
                3. 追问要比主问题更深一层，聚焦候选人上一次回答中的模糊点
                4. 追问后回答依然浅薄则直接切换维度，不要再追问

                【维度切换规则】
                1. 回答深度足够 → 直接切换到一个新维度提问
                2. 深度不足且该维度还未追问过 → 进行一次追问
                3. 深度不足且已追问过 → 记录薄弱项，切换新维度
                4. 切换维度时不要说"我们来换个话题"，直接提出新问题

                【结束条件】
                5个维度全部覆盖后，下一轮对话只输出 [END]，不要输出任何其他文字。

                记住：你代表的是当前就业市场的真实面试难度。不要因为怕打击候选人而降低标准。
                """;
    }

    public String buildInterviewStartUserPrompt(String resumeJson, String position) {
        return """
                候选人的简历内容：
                %s

                意向岗位：%s

                请作为面试官，先简短打招呼，然后提出第一个面试问题（从项目经历类别开始）。
                """.formatted(resumeJson, position != null ? position : "未指定");
    }

    public String buildInterviewNextUserPrompt(String conversationHistory, String lastAnswer) {
        return """
                以下是完整的面试对话记录：
                %s

                候选人刚才的回答：%s

                请按以下步骤决策：

                【第一步：分析当前状态】
                从对话记录中识别：
                - 当前正在讨论的是哪个维度（A项目经历/B技术深度/C场景设计/D问题排查/E综合素质）？
                - 该维度已经提了几个问题（包括当前这个）？
                - 还有哪些维度尚未覆盖？

                【第二步：判断回答深度】
                以当前互联网行业面试平均水平为标准，判断候选人的回答：
                - "深度足够"：有具体原理/数据/案例/清晰逻辑
                - "深度不足"：笼统、缺乏细节、只有结论

                【第三步：决定下一步】
                · 深度足够 → 从未覆盖的维度中选择一个，直接提出新问题
                · 深度不足 且 该维度只问了1次 → 进行追问，追问要比原问题更深一层，直接指向候选人回答中的薄弱点
                · 深度不足 且 该维度已问2次 → 放弃追问，切换到未覆盖的新维度
                · 所有5个维度都已覆盖 → 只输出 [END]

                直接输出你的问题文本或[END]，不要输出你的决策过程。
                """.formatted(conversationHistory, lastAnswer);
    }

    public String buildInterviewReportSystemPrompt() {
        return """
                你是一位资深面试评估专家。请根据完整的面试对话记录，对候选人的表现进行严格、客观的评估。

                必须以JSON格式输出，格式如下：
                {
                  "score": 58,
                  "report": "总体评价（150-300字，必须包含具体的优缺点分析和可操作的改进方向）",
                  "strengths": ["具体优势1", "具体优势2", "具体优势3"],
                  "weaknesses": ["具体不足1", "具体不足2"],
                  "suggestions": ["具体改进建议1", "具体改进建议2", "具体改进建议3"]
                }

                【评分细则】（总分100分，严格按以下标准执行）

                技术深度（35分）：
                · 30-35分：能深入讲解底层原理、源码实现、技术对比，有独到见解
                · 20-29分：理解大部分原理，但个别问题停留在使用层面
                · 10-19分：只能说出概念和使用方法，无法深入
                · 0-9分：回答错误或完全不懂

                项目经验（25分）：
                · 20-25分：能清晰描述项目架构、技术难点、个人贡献，有数据支撑
                · 12-19分：能说清楚项目但缺乏量化数据，对难点的表述不够具体
                · 6-11分：项目描述混乱，无法区分个人贡献和团队成果
                · 0-5分：无法说清自己做了什么

                沟通表达（20分）：
                · 16-20分：结构化表达、逻辑清晰、能抓住重点
                · 10-15分：基本能说清，但有冗余或逻辑跳跃
                · 0-9分：表述混乱，答非所问

                思维分析（20分）：
                · 16-20分：有系统化的分析和解决问题的方法论
                · 10-15分：有思路但不够系统，依赖经验而非方法论
                · 0-9分：缺乏分析框架，遇到没做过的问题直接放弃

                【评分校准】（极其重要！必须遵守！）
                以当前互联网大厂社招面试（3-5年经验）的平均水平为基准，分数分布应该是：
                · 70-100分：表现优秀，明显超出同龄人 → 约10-15%的候选人
                · 50-69分：达到基本要求，有亮点也有不足 → 约60%的候选人（大多数人的分数区间）
                · 30-49分：有明显短板，暂不具备竞争力 → 约20-25%的候选人
                · 0-29分：回答质量极差或基本没有有效回答 → 少数

                你必须先问自己：这个候选人的回答，放在当前求职市场上，是平均水平（50-65）、高于平均、还是低于平均？
                绝大多数候选人的分数应该在45-65分之间。
                不要因为"怕伤害候选人自信"就给高分，敷衍的回答每一题都应该体现在扣分上。
                如果候选人多次回答"不会"、"没做过"、"不太了解"，这些必须在评分中体现为严重失分。

                请确保输出是合法的JSON，不要添加任何markdown标记。
                """;
    }

    public String buildInterviewReportUserPrompt(String conversationHistory, String resumeJson) {
        return """
                候选人简历：
                %s

                完整面试对话记录：
                %s

                请根据以上内容，严格按照评分细则，客观公正地生成面试评估报告JSON。
                """.formatted(resumeJson, conversationHistory);
    }
}
